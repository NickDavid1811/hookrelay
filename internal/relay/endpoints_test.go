func TestDynamicEndpointCreationAndDelivery(t *testing.T) {
	p := filepath.Join(t.TempDir(), "dynamic.db")
	db, err := Open(p)
	if err != nil {
		t.Fatal(err)
	}
	defer db.Close()

	s := &Service{DB: db, AllowLoopbackEndpoints: true}
	cfg := Config{Clients: []ClientConfig{
		{ID: "client-a", TokenEnv: "TEST_TOKEN"},
	}}
	if err := s.ApplyConfig(cfg, func(name string) string { return testToken }); err != nil {
		t.Fatal(err)
	}

	var receivedCount atomic.Int32
	var receivedSecret string
	var receivedBody string

	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		b, _ := io.ReadAll(r.Body)
		receivedBody = string(b)
		ts := r.Header.Get("X-Webhook-Timestamp")
		sig := r.Header.Get("X-Webhook-Signature")
		if Signature(receivedSecret, ts, b) != sig {
			t.Errorf("signature mismatch: expected with secret %s, got %s", receivedSecret, sig)
		}
		receivedCount.Add(1)
		w.WriteHeader(http.StatusOK)
	}))
	defer srv.Close()

	handler := s.Handler()

	// 1. Unauthorized attempt
	req := httptest.NewRequest("POST", "/api/v1/endpoints", strings.NewReader(`{"id":"dyn-1","url":"`+srv.URL+`"}`))
	rec := httptest.NewRecorder()
	handler.ServeHTTP(rec, req)
	if rec.Code != http.StatusUnauthorized {
		t.Fatalf("expected 401 unauthorized, got %d", rec.Code)
	}

	// 2. Successful creation with auto-generated secret
	createBody := fmt.Sprintf(`{"id":"dyn-1","url":"%s","allow_loopback":true}`, srv.URL)
	req = httptest.NewRequest("POST", "/api/v1/endpoints", strings.NewReader(createBody))
	req.Header.Set("Authorization", "Bearer "+testToken)
	rec = httptest.NewRecorder()
	handler.ServeHTTP(rec, req)

	if rec.Code != http.StatusCreated {
		t.Fatalf("expected 201 created, got %d: %s", rec.Code, rec.Body.String())
	}

	var createdResp struct {
		ID        string `json:"id"`
		URL       string `json:"url"`
		Secret    string `json:"secret"`
		CreatedAt int64  `json:"created_at"`
	}
	if err := json.Unmarshal(rec.Body.Bytes(), &createdResp); err != nil {
		t.Fatalf("failed to decode response: %v", err)
	}
	if createdResp.ID != "dyn-1" {
		t.Fatalf("unexpected id %s", createdResp.ID)
	}
	if !strings.HasPrefix(createdResp.Secret, "hrsec_") {
		t.Fatalf("expected autogenerated secret to start with hrsec_, got %s", createdResp.Secret)
	}
	receivedSecret = createdResp.Secret

	// 3. Publish an event targeting this dynamic endpoint
	pubReq := httptest.NewRequest("POST", "/api/v1/publish", strings.NewReader(`{"endpoint_id":"dyn-1","event_type":"order.created","payload":{"order_id":"123"}}`))
	pubReq.Header.Set("Authorization", "Bearer "+testToken)
	pubReq.Header.Set("Idempotency-Key", "dyn-idem-1")
	pubRec := httptest.NewRecorder()
	handler.ServeHTTP(pubRec, pubReq)

	if pubRec.Code != http.StatusAccepted {
		t.Fatalf("expected 202 accepted, got %d: %s", pubRec.Code, pubRec.Body.String())
	}

	// 4. Process delivery with single worker step
	ctx, cancel := context.WithCancel(context.Background())
	app := s.application()
	done := make(chan error, 1)
	go func() {
		done <- app.Run(ctx)
	}()

	time.Sleep(100 * time.Millisecond)
	cancel()
	<-done

	if receivedCount.Load() != 1 {
		t.Fatalf("expected 1 delivery received, got %d", receivedCount.Load())
	}
	if receivedBody != `{"order_id":"123"}` {
		t.Fatalf("unexpected body: %s", receivedBody)
	}

	// 5. Verify persistence across service restart
	s2 := &Service{DB: db, AllowLoopbackEndpoints: true}
	if err = s2.Initialize(context.Background()); err != nil {
		t.Fatal(err)
	}
	ep, ok, err := s2.resolveEndpoint(context.Background(), "dyn-1")
	if err != nil || !ok || ep.Secret != createdResp.Secret {
		t.Fatalf("recovered endpoint: ok=%v err=%v", ok, err)
	}

}

func TestDynamicEndpointValidationAndIsolation(t *testing.T) {
	p := filepath.Join(t.TempDir(), "val.db")
	db, err := Open(p)
	if err != nil {
		t.Fatal(err)
	}
	defer db.Close()

	s := &Service{DB: db}
	cfg := Config{Clients: []ClientConfig{
		{ID: "client-a", TokenEnv: "TOKEN_A"},
		{ID: "client-b", TokenEnv: "TOKEN_B"},
	}}
	tokenA := "token-a-1234567890123"
	tokenB := "token-b-1234567890123"
	if err := s.ApplyConfig(cfg, func(name string) string {
		if name == "TOKEN_A" {
			return tokenA
		}
		return tokenB
	}); err != nil {
		t.Fatal(err)
	}

	handler := s.Handler()

	// SSRF rejection on loopback without allow_loopback
	req := httptest.NewRequest("POST", "/api/v1/endpoints", strings.NewReader(`{"id":"ssrf-1","url":"http://127.0.0.1:9090"}`))
	req.Header.Set("Authorization", "Bearer "+tokenA)
	rec := httptest.NewRecorder()
	handler.ServeHTTP(rec, req)
	if rec.Code != http.StatusBadRequest && rec.Code != http.StatusUnprocessableEntity {
		t.Fatalf("expected 400 or 422 for SSRF, got %d: %s", rec.Code, rec.Body.String())
	}

	// Short secret rejection (< 16 chars)
	req = httptest.NewRequest("POST", "/api/v1/endpoints", strings.NewReader(`{"id":"short-sec","url":"https://example.com/webhook","secret":"short"}`))
	req.Header.Set("Authorization", "Bearer "+tokenA)
	rec = httptest.NewRecorder()
	handler.ServeHTTP(rec, req)
	if rec.Code != http.StatusBadRequest {
		t.Fatalf("expected 400 for short secret, got %d: %s", rec.Code, rec.Body.String())
	}

	// Successful creation with custom secret >= 16 chars
	customSec := "hrsec_customsecret1234567890"
	req = httptest.NewRequest("POST", "/api/v1/endpoints", strings.NewReader(fmt.Sprintf(`{"id":"ep-a","url":"https://example.com/webhook","secret":"%s"}`, customSec)))
	req.Header.Set("Authorization", "Bearer "+tokenA)
	rec = httptest.NewRecorder()
	handler.ServeHTTP(rec, req)
	if rec.Code != http.StatusCreated {
		t.Fatalf("expected 201 for valid endpoint, got %d: %s", rec.Code, rec.Body.String())
	}

	// Duplicate endpoint creation
	req = httptest.NewRequest("POST", "/api/v1/endpoints", strings.NewReader(`{"id":"ep-a","url":"https://example.com/other"}`))
	req.Header.Set("Authorization", "Bearer "+tokenA)
	rec = httptest.NewRecorder()
	handler.ServeHTTP(rec, req)
	if rec.Code != http.StatusConflict && rec.Code != http.StatusBadRequest {
		t.Fatalf("expected 409 conflict for duplicate endpoint, got %d: %s", rec.Code, rec.Body.String())
	}

	// GET /api/v1/endpoints returns ep-a for client-a
	req = httptest.NewRequest("GET", "/api/v1/endpoints", nil)
	req.Header.Set("Authorization", "Bearer "+tokenA)
	rec = httptest.NewRecorder()
	handler.ServeHTTP(rec, req)
	if rec.Code != http.StatusOK {
		t.Fatalf("expected 200, got %d: %s", rec.Code, rec.Body.String())
	}
	var epsA []struct {
		ID  string `json:"id"`
		URL string `json:"url"`
	}
	if err := json.Unmarshal(rec.Body.Bytes(), &epsA); err != nil || len(epsA) != 1 || epsA[0].ID != "ep-a" {
		t.Fatalf("unexpected endpoints list for client-a: %s", rec.Body.String())
	}

	// GET /api/v1/endpoints returns empty list for client-b (isolation)
	req = httptest.NewRequest("GET", "/api/v1/endpoints", nil)
	req.Header.Set("Authorization", "Bearer "+tokenB)
	rec = httptest.NewRecorder()
	handler.ServeHTTP(rec, req)
	if rec.Code != http.StatusOK {
		t.Fatalf("expected 200, got %d: %s", rec.Code, rec.Body.String())
	}
	var epsB []struct {
		ID  string `json:"id"`
		URL string `json:"url"`
	}
	if err := json.Unmarshal(rec.Body.Bytes(), &epsB); err != nil || len(epsB) != 0 {
		t.Fatalf("expected empty endpoints list for client-b, got: %s", rec.Body.String())
	}

	// Client-b cannot publish to Client-a's endpoint
	pubReq := httptest.NewRequest("POST", "/api/v1/publish", strings.NewReader(`{"endpoint_id":"ep-a","event_type":"ev","payload":{}}`))
	pubReq.Header.Set("Authorization", "Bearer "+tokenB)
	pubReq.Header.Set("Idempotency-Key", "b-publish-a")
	pubRec := httptest.NewRecorder()
	handler.ServeHTTP(pubRec, pubReq)
	if pubRec.Code != http.StatusNotFound && pubRec.Code != http.StatusBadRequest {
		t.Fatalf("expected 404 or 400 when publishing to another client's endpoint, got %d: %s", pubRec.Code, pubRec.Body.String())
	}
}

func TestEndpointGetAndDeleteLifecycle(t *testing.T) {
	p := filepath.Join(t.TempDir(), "lifecycle.db")
	db, err := Open(p)
	if err != nil {
		t.Fatal(err)
	}
	defer db.Close()

	s := &Service{DB: db}
	tokenA := "test-token-client-a-12345"
	tokenB := "test-token-client-b-12345"
	cfg := Config{
		Clients: []ClientConfig{
			{ID: "client-a", TokenEnv: "TOKEN_A"},
			{ID: "client-b", TokenEnv: "TOKEN_B"},
		},
	}
	if err := s.ApplyConfig(cfg, func(name string) string {
		if name == "TOKEN_A" {
			return tokenA
		}
		return tokenB
	}); err != nil {
		t.Fatal(err)
	}

	handler := s.Handler()

	// 1. Create endpoint for client-a
	createReq := httptest.NewRequest("POST", "/api/v1/endpoints", strings.NewReader(`{"id":"ep-lifecycle","url":"https://example.com/webhook"}`))
	createReq.Header.Set("Authorization", "Bearer "+tokenA)
	createRec := httptest.NewRecorder()
	handler.ServeHTTP(createRec, createReq)
	if createRec.Code != http.StatusCreated {
		t.Fatalf("expected 201 created, got %d: %s", createRec.Code, createRec.Body.String())
	}

	// Dynamic endpoints are resolved from committed storage, not registered before commit.
	if _, ok, err := s.resolveEndpoint(context.Background(), "ep-lifecycle"); err != nil || !ok {
		t.Fatal(ok, err)
	}

	// 2. GET /api/v1/endpoints/ep-lifecycle as client-a -> 200 OK
	getReq := httptest.NewRequest("GET", "/api/v1/endpoints/ep-lifecycle", nil)
	getReq.Header.Set("Authorization", "Bearer "+tokenA)
	getRec := httptest.NewRecorder()
	handler.ServeHTTP(getRec, getReq)
	if getRec.Code != http.StatusOK {
		t.Fatalf("expected 200, got %d: %s", getRec.Code, getRec.Body.String())
	}
	var epRecord core.EndpointRecord
	if err := json.Unmarshal(getRec.Body.Bytes(), &epRecord); err != nil || epRecord.ID != "ep-lifecycle" || epRecord.URL != "https://example.com/webhook" {
		t.Fatalf("unexpected endpoint record: %s", getRec.Body.String())
	}

	// 3. GET /api/v1/endpoints/ep-lifecycle as client-b -> 404 (tenant isolation)
	getReqB := httptest.NewRequest("GET", "/api/v1/endpoints/ep-lifecycle", nil)
	getReqB.Header.Set("Authorization", "Bearer "+tokenB)
	getRecB := httptest.NewRecorder()
	handler.ServeHTTP(getRecB, getReqB)
	if getRecB.Code != http.StatusNotFound {
		t.Fatalf("expected 404 for other client, got %d: %s", getRecB.Code, getRecB.Body.String())
	}

	// 4. GET non-existent endpoint -> 404
	missingReq := httptest.NewRequest("GET", "/api/v1/endpoints/ep-missing", nil)
	missingReq.Header.Set("Authorization", "Bearer "+tokenA)
	missingRec := httptest.NewRecorder()
	handler.ServeHTTP(missingRec, missingReq)
	if missingRec.Code != http.StatusNotFound {
		t.Fatalf("expected 404 for missing endpoint, got %d", missingRec.Code)
	}

	// 5. DELETE as client-b -> 404 (cannot delete another client's endpoint)
	delReqB := httptest.NewRequest("DELETE", "/api/v1/endpoints/ep-lifecycle", nil)
	delReqB.Header.Set("Authorization", "Bearer "+tokenB)
	delRecB := httptest.NewRecorder()
	handler.ServeHTTP(delRecB, delReqB)
	if delRecB.Code != http.StatusNotFound {
		t.Fatalf("expected 404 when unauthorized client attempts delete, got %d: %s", delRecB.Code, delRecB.Body.String())
	}

	// 6. DELETE as client-a -> 204 No Content
	delReqA := httptest.NewRequest("DELETE", "/api/v1/endpoints/ep-lifecycle", nil)
	delReqA.Header.Set("Authorization", "Bearer "+tokenA)
	delRecA := httptest.NewRecorder()
	handler.ServeHTTP(delRecA, delReqA)
	if delRecA.Code != http.StatusNoContent {
		t.Fatalf("expected 204 No Content, got %d: %s", delRecA.Code, delRecA.Body.String())
	}

	if _, _, err := s.resolveEndpoint(context.Background(), "ep-lifecycle"); err == nil {
		t.Fatal("deleted destination still resolves")
	}

	// 7. GET /api/v1/endpoints/ep-lifecycle after delete -> 404
	getReqAfter := httptest.NewRequest("GET", "/api/v1/endpoints/ep-lifecycle", nil)
	getReqAfter.Header.Set("Authorization", "Bearer "+tokenA)
	getRecAfter := httptest.NewRecorder()
	handler.ServeHTTP(getRecAfter, getReqAfter)
	if getRecAfter.Code != http.StatusNotFound {
		t.Fatalf("expected 404 after deletion, got %d: %s", getRecAfter.Code, getRecAfter.Body.String())
	}

	// 8. DELETE already-deleted endpoint -> 404
	delReqAgain := httptest.NewRequest("DELETE", "/api/v1/endpoints/ep-lifecycle", nil)
	delReqAgain.Header.Set("Authorization", "Bearer "+tokenA)
	delRecAgain := httptest.NewRecorder()
	handler.ServeHTTP(delRecAgain, delReqAgain)
	if delRecAgain.Code != http.StatusNotFound {
		t.Fatalf("expected 404 on deleting already inactive endpoint, got %d: %s", delRecAgain.Code, delRecAgain.Body.String())
	}

	// 9. Publish to deleted endpoint -> 404
	pubReq := httptest.NewRequest("POST", "/api/v1/publish", strings.NewReader(`{"endpoint_id":"ep-lifecycle","event_type":"user.created","payload":{"id":1}}`))
	pubReq.Header.Set("Authorization", "Bearer "+tokenA)
	pubReq.Header.Set("Idempotency-Key", "pub-to-deleted")
	pubRec := httptest.NewRecorder()
	handler.ServeHTTP(pubRec, pubReq)
	if pubRec.Code != http.StatusNotFound {
		t.Fatalf("expected 404 when publishing to deleted endpoint, got %d: %s", pubRec.Code, pubRec.Body.String())
	}
}
